#!/usr/bin/env python3
"""
engines/report/generate_rdd_sql.py
----------------------------------
Generates sql/03-rdd-definitions.sql from the JSON RDD definitions in
engines/report/<report>.json (the JSON files remain the single source of truth).

Tables created in [ErpReporting]:
  - dbo.RddTable
  - dbo.RddColumn (RddId, TableName, ColumnName, Exclude bit, ColumnOrder int)
  - dbo.RddRelationship
Procedure created in [ErpReporting]:
  - dbo.usp_SetRddExclude(@RddId, @TableName, @ColumnName, @Exclude)
"""

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
JSON_DIR = REPO_ROOT / "engines" / "report"
OUT_SQL = REPO_ROOT / "sql" / "03-rdd-definitions.sql"

RDD_FILES = [
    "PackSlip.json",
    "OrderAck.json",
    "ARForm.json",
    "OpenOrders.json",
]


def sql_str(val: str) -> str:
    if val is None:
        return "NULL"
    return "N'" + str(val).replace("'", "''") + "'"


def generate_sql() -> str:
    lines = [
        "/* =============================================================================",
        "   sql/03-rdd-definitions.sql",
        "   -----------------------------------------------------------------------------",
        "   AUTO-GENERATED by engines/report/generate_rdd_sql.py from engines/report/<report>.json.",
        "   Do not hand-edit the INSERT statements; update engines/report/<report>.json and re-run",
        "   `python3 engines/report/generate_rdd_sql.py`.",
        "",
        "   Target:   Microsoft SQL Server 2016+",
        "   Database: [ErpReporting]",
        "   Objects:",
        "     - dbo.RddTable",
        "     - dbo.RddColumn (RddId, TableName, ColumnName, Exclude bit, ColumnOrder int)",
        "     - dbo.RddRelationship",
        "     - dbo.usp_SetRddExclude(@RddId, @TableName, @ColumnName, @Exclude)",
        "",
        "   Citations & Banners:",
        "     - docs/reference/01-ssrs-forms.md §3.1-3.14 [S12, S13, S14, S15, S16, S17, S25]",
        "     - Approved Default 20 (docs/reference/decisions.md): Un-excluding a column via",
        "       dbo.usp_SetRddExclude affects only subsequent dbo.usp_StageEpicorReport runs.",
        "     - Default chosen for the lab, not confirmed against Epicor: dbo.RddTable,",
        "       dbo.RddColumn, dbo.RddRelationship, and dbo.usp_SetRddExclude are lab SQL",
        "       stand-ins for Epicor RDD Maintenance metadata until the console exists.",
        "   ============================================================================= */",
        "",
        "SET NOCOUNT ON;",
        "",
        "IF DB_ID('ErpReporting') IS NULL",
        "BEGIN",
        "    CREATE DATABASE [ErpReporting];",
        "END;",
        "GO",
        "",
        "USE [ErpReporting];",
        "GO",
        "",
        "/* =============================================================================",
        "   1. METADATA TABLE CLEANUP & DDL",
        "   ============================================================================= */",
        "",
        "IF OBJECT_ID('dbo.RddRelationship', 'U') IS NOT NULL DROP TABLE dbo.RddRelationship;",
        "IF OBJECT_ID('dbo.RddColumn', 'U') IS NOT NULL DROP TABLE dbo.RddColumn;",
        "IF OBJECT_ID('dbo.RddTable', 'U') IS NOT NULL DROP TABLE dbo.RddTable;",
        "GO",
        "",
        "CREATE TABLE dbo.RddTable (",
        "    RddId       NVARCHAR(50)  NOT NULL,",
        "    TableName   NVARCHAR(128) NOT NULL,",
        "    SchemaName  NVARCHAR(50)  NOT NULL,",
        "    TableType   NVARCHAR(20)  NOT NULL,",
        "    Description NVARCHAR(500) NULL,",
        "    CONSTRAINT PK_RddTable PRIMARY KEY CLUSTERED (RddId, TableName)",
        ");",
        "",
        "CREATE TABLE dbo.RddColumn (",
        "    RddId       NVARCHAR(50)  NOT NULL,",
        "    TableName   NVARCHAR(128) NOT NULL,",
        "    ColumnName  NVARCHAR(128) NOT NULL,",
        "    Exclude     BIT           NOT NULL DEFAULT 0,",
        "    ColumnOrder INT           NOT NULL DEFAULT 0,",
        "    CONSTRAINT PK_RddColumn PRIMARY KEY CLUSTERED (RddId, TableName, ColumnName),",
        "    CONSTRAINT FK_RddColumn_RddTable FOREIGN KEY (RddId, TableName)",
        "        REFERENCES dbo.RddTable (RddId, TableName)",
        ");",
        "",
        "CREATE TABLE dbo.RddRelationship (",
        "    RddId            NVARCHAR(50)  NOT NULL,",
        "    RelationshipName NVARCHAR(128) NOT NULL,",
        "    ParentTable      NVARCHAR(128) NOT NULL,",
        "    ChildTable       NVARCHAR(128) NOT NULL,",
        "    RelationType     NVARCHAR(20)  NOT NULL DEFAULT 'Output',",
        "    RelationshipKeys NVARCHAR(500) NOT NULL,",
        "    CONSTRAINT PK_RddRelationship PRIMARY KEY CLUSTERED (RddId, RelationshipName)",
        ");",
        "GO",
        "",
        "/* =============================================================================",
        "   2. SEED RDD DEFINITIONS (FROM engines/report/<report>.json)",
        "   ============================================================================= */",
        "",
    ]

    for filename in RDD_FILES:
        path = JSON_DIR / filename
        data = json.loads(path.read_text(encoding="utf-8"))
        rdd_id = data["rddId"]
        lines.append(f"-- -----------------------------------------------------------------------------")
        lines.append(f"-- RDD: {rdd_id} (source: engines/report/{filename})")
        lines.append(f"-- -----------------------------------------------------------------------------")

        # RddTable inserts
        for tbl in data.get("tables", []):
            t_name = tbl["tableName"]
            s_name = tbl.get("schemaName", "Erp")
            t_type = tbl.get("tableType", "Data")
            desc = tbl.get("description", "")
            lines.append(
                f"INSERT INTO dbo.RddTable (RddId, TableName, SchemaName, TableType, Description) "
                f"VALUES ({sql_str(rdd_id)}, {sql_str(t_name)}, {sql_str(s_name)}, {sql_str(t_type)}, {sql_str(desc)});"
            )

        lines.append("")

        # RddColumn inserts
        for tbl in data.get("tables", []):
            t_name = tbl["tableName"]
            cols = tbl.get("columns")
            if not cols:
                cols = [
                    {"columnName": c, "exclude": False}
                    for c in tbl.get("includedColumns", [])
                ] + [
                    {"columnName": c, "exclude": True}
                    for c in tbl.get("excludedColumns", [])
                ]
            for idx, col in enumerate(cols, start=1):
                c_name = col["columnName"]
                excl_bit = 1 if col.get("exclude", False) else 0
                lines.append(
                    f"INSERT INTO dbo.RddColumn (RddId, TableName, ColumnName, Exclude, ColumnOrder) "
                    f"VALUES ({sql_str(rdd_id)}, {sql_str(t_name)}, {sql_str(c_name)}, {excl_bit}, {idx});"
                )
            lines.append("")

        # RddRelationship inserts
        rels = data.get("relationships", [])
        for rel in rels:
            r_name = rel["relationshipName"]
            p_tbl = rel["parentTable"]
            c_tbl = rel["childTable"]
            r_type = rel.get("relationType", "Output")
            key_pairs = ", ".join(
                f"{f['parentField']}={f['childField']}" for f in rel.get("fields", [])
            )
            lines.append(
                f"INSERT INTO dbo.RddRelationship (RddId, RelationshipName, ParentTable, ChildTable, RelationType, RelationshipKeys) "
                f"VALUES ({sql_str(rdd_id)}, {sql_str(r_name)}, {sql_str(p_tbl)}, {sql_str(c_tbl)}, {sql_str(r_type)}, {sql_str(key_pairs)});"
            )
        if rels:
            lines.append("")

    lines.extend([
        "GO",
        "",
        "/* =============================================================================",
        "   3. LEARNER STAND-IN FOR RDD MAINTENANCE: dbo.usp_SetRddExclude",
        "   ============================================================================= */",
        "",
        "IF OBJECT_ID('dbo.usp_SetRddExclude', 'P') IS NOT NULL",
        "    DROP PROCEDURE dbo.usp_SetRddExclude;",
        "GO",
        "",
        "CREATE PROCEDURE dbo.usp_SetRddExclude",
        "    @RddId      NVARCHAR(50),",
        "    @TableName  NVARCHAR(128),",
        "    @ColumnName NVARCHAR(128),",
        "    @Exclude    BIT",
        "AS",
        "BEGIN",
        "    SET NOCOUNT ON;",
        "",
        "    IF NOT EXISTS (",
        "        SELECT 1",
        "        FROM dbo.RddColumn",
        "        WHERE RddId = @RddId",
        "          AND TableName = @TableName",
        "          AND ColumnName = @ColumnName",
        "    )",
        "    BEGIN",
        "        RAISERROR('Column [%s].[%s] was not found in RDD [%s].', 16, 1, @TableName, @ColumnName, @RddId);",
        "        RETURN;",
        "    END;",
        "",
        "    UPDATE dbo.RddColumn",
        "    SET Exclude = @Exclude",
        "    WHERE RddId = @RddId",
        "      AND TableName = @TableName",
        "      AND ColumnName = @ColumnName;",
        "",
        "    -- Return the updated row so the learner can verify the new Exclude state",
        "    SELECT",
        "        RddId,",
        "        TableName,",
        "        ColumnName,",
        "        Exclude",
        "    FROM dbo.RddColumn",
        "    WHERE RddId = @RddId",
        "      AND TableName = @TableName",
        "      AND ColumnName = @ColumnName;",
        "END;",
        "GO",
        "",
    ])

    return "\n".join(lines)


def main() -> None:
    sql_text = generate_sql()
    OUT_SQL.write_text(sql_text, encoding="utf-8")
    print(f"Generated {OUT_SQL.relative_to(REPO_ROOT)} ({len(sql_text.splitlines())} lines).")


if __name__ == "__main__":
    main()
